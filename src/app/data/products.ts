/** Lowest price across a product's sizes — the "from" price on a card. */
export const priceFrom = (p: Product) =>
  Math.min(...p.variants.map((v) => v.priceTzs));

export const totalStock = (p: Product) =>
  p.variants.reduce((n, v) => n + v.stock, 0);
